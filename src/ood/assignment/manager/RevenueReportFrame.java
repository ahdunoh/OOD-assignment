    private void btnGenerateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerateActionPerformed
        String reportType = cmbReportType.getSelectedItem().toString();
        int year = Integer.parseInt(cmbYear.getSelectedItem().toString());
        int month = cmbMonth.getSelectedIndex() + 1;

        javax.swing.table.DefaultTableModel model =
        (javax.swing.table.DefaultTableModel) tblRevenue.getModel();

        model.setRowCount(0);

        int paidTransactions = 0;
        java.math.BigDecimal totalRevenue = java.math.BigDecimal.ZERO;

        try {
            java.nio.file.Path file =
                java.nio.file.Paths.get("payments.txt");

            if (!java.nio.file.Files.exists(file)) {
                javax.swing.JOptionPane.showMessageDialog(
                    this, "payments.txt not found!");
                return;
            }

            for (String line : java.nio.file.Files.readAllLines(
                    file, java.nio.charset.StandardCharsets.UTF_8)) {

                if (line.trim().isEmpty()) {
                    continue;
                }

                String[] data = line.split("\\s*,\\s*", -1);

                if (data.length != 6) {
                    continue;
                }

                // paymentID, username, classID, amount, date, status
                if (!data[5].equalsIgnoreCase("paid")) {
                    continue;
                }

                java.time.LocalDate date =
                    java.time.LocalDate.parse(data[4]);

                boolean match = date.getYear() == year;

                if (reportType.equals("Monthly")) {
                    match = match && date.getMonthValue() == month;
                }

                if (match) {
                    paidTransactions++;

                    totalRevenue = totalRevenue.add(
                        new java.math.BigDecimal(data[3])
                    );
                }
            }

            String period = reportType.equals("Monthly")
                ? cmbMonth.getSelectedItem() + " " + year
                : String.valueOf(year);

            model.addRow(new Object[]{
                period,
                paidTransactions,
                totalRevenue.setScale(
                    2, java.math.RoundingMode.HALF_UP).toPlainString()
            });

            lblRegistrations.setText(
                "Paid Transactions: " + paidTransactions);

            lblRevenue.setText(
                "Total Revenue: RM " + totalRevenue.setScale(
                    2, java.math.RoundingMode.HALF_UP).toPlainString());

        } catch (java.io.IOException |
                 java.time.format.DateTimeParseException |
                 NumberFormatException ex) {

            javax.swing.JOptionPane.showMessageDialog(
                this, "Report error: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnGenerateActionPerformed

