    private void UpdateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UpdateButtonActionPerformed
        int selectedRow = tblAdministrators.getSelectedRow();

        if (selectedRow == -1) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Please select an administrator.");
            return;
        }

        String oldID = tblAdministrators.getValueAt(selectedRow, 0).toString();

        String newID = jTextField1.getText().trim();
        String newName = jTextField2.getText().trim();
        String newPhone = jTextField3.getText().trim();

        if (newID.isEmpty() || newName.isEmpty() || newPhone.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Please fill in all fields.");
            return;
        }

        if (newID.contains("|") || newName.contains("|")
                || newPhone.contains("|")
                || newID.contains("\n") || newName.contains("\n")
                || newPhone.contains("\n")
                || newID.contains("\r") || newName.contains("\r")
                || newPhone.contains("\r")) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Invalid characters in the input.");
            return;
        }

        if (!newPhone.matches("\\+?[0-9]{9,15}")) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Please enter a valid phone number.");
            return;
        }

        try {
            java.nio.file.Path file
                    = java.nio.file.Paths.get("administrators.txt");

            java.util.List<String> lines
                    = java.nio.file.Files.readAllLines(file);

            java.util.List<String> updated = new java.util.ArrayList<>();
            boolean found = false;

            for (String line : lines) {
                String[] data = line.split("\\|", -1);

                if (data.length == 3 && data[0].equals(oldID)) {
                    updated.add(newID + "|" + newName + "|" + newPhone);
                    found = true;
                } else {
                    if (data.length == 3
                            && data[0].equalsIgnoreCase(newID)
                            && !data[0].equals(oldID)) {
                        javax.swing.JOptionPane.showMessageDialog(
                                this, "Administrator ID already exists.");
                        return;
                    }
                    updated.add(line);
                }
            }

            if (!found) {
                javax.swing.JOptionPane.showMessageDialog(
                        this, "Administrator not found.");
                return;
            }

            java.nio.file.Files.write(file, updated,
                    java.nio.charset.StandardCharsets.UTF_8);

            loadAdministratorTable();

            javax.swing.JOptionPane.showMessageDialog(
                    this, "Administrator updated successfully!");

        } catch (java.io.IOException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Update failed: " + ex.getMessage());
        }
    }//GEN-LAST:event_UpdateButtonActionPerformed

    private void DeleteButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteButtonActionPerformed
        int selectedRow = tblAdministrators.getSelectedRow();

        if (selectedRow == -1) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Please select an administrator.");
            return;
        }

        String adminID = tblAdministrators.getValueAt(selectedRow, 0).toString();

        int confirm = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to delete " + adminID + "?",
                "Confirm Delete",
                javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (confirm != javax.swing.JOptionPane.YES_OPTION) {
            return;
        }

        try {
            java.nio.file.Path file
                    = java.nio.file.Paths.get("administrators.txt");

            java.util.List<String> lines
                    = java.nio.file.Files.readAllLines(
                            file, java.nio.charset.StandardCharsets.UTF_8);

            java.util.List<String> remaining
                    = new java.util.ArrayList<>();

            boolean found = false;

            for (String line : lines) {
                String[] data = line.split("\\|", -1);

                if (data.length == 3 && data[0].equals(adminID)) {
                    found = true;
                } else {
                    remaining.add(line);
                }
            }

            if (!found) {
                javax.swing.JOptionPane.showMessageDialog(
                        this, "Administrator not found.");
                return;
            }

            java.nio.file.Files.write(
                    file, remaining, java.nio.charset.StandardCharsets.UTF_8);

            loadAdministratorTable();

            javax.swing.JOptionPane.showMessageDialog(
                    this, "Administrator deleted successfully!");

        } catch (java.io.IOException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Delete failed: " + ex.getMessage());
        }
    }//GEN-LAST:event_DeleteButtonActionPerformed

