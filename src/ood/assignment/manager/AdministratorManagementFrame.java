    private void AddButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AddButtonActionPerformed
        // TODO add your handling code here:
        String adminID = jTextField1.getText().trim();
        String adminName = jTextField2.getText().trim();
        String phone = jTextField3.getText().trim();
        
        if (adminID.matches(".*[|\\r\\n].*")
        || adminName.matches(".*[|\\r\\n].*")
        || phone.matches(".*[|\\r\\n].*")) 
        {
        JOptionPane.showMessageDialog(
        this, "Invalid characters detected.");
        return;
        }

        if (adminID.isEmpty() || adminName.isEmpty() || phone.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Please fill in all fields.");
            return;
        }

        if (!phone.matches("\\+?[0-9]{9,15}")) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Please enter a valid phone number.");
            return;
        }

        String record = adminID + "|" + adminName + "|" + phone;

        try {
            java.nio.file.Path file
                    = java.nio.file.Paths.get("administrators.txt");
            if (java.nio.file.Files.exists(file)) {
                for (String line : java.nio.file.Files.readAllLines(file)) {
                    String[] fields = line.split("\\|", -1);

                    if (fields.length > 0
                            && fields[0].equalsIgnoreCase(adminID)) {
                        javax.swing.JOptionPane.showMessageDialog(
                                this, "Administrator ID already exists.");
                        return;
                    }
                }
            }

            java.nio.file.Files.write(
                    file,
                    java.util.Collections.singletonList(record),
                    java.nio.charset.StandardCharsets.UTF_8,
                    java.nio.file.StandardOpenOption.CREATE,
                    java.nio.file.StandardOpenOption.APPEND
            );

            loadAdministratorTable();
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Administrator added successfully!");

            jTextField1.setText("");
            jTextField2.setText("");
            jTextField3.setText("");

        } catch (java.io.IOException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Could not save administrator: " + ex.getMessage());
        }
    }

    private void loadAdministratorTable() {

        javax.swing.table.DefaultTableModel model
                = (javax.swing.table.DefaultTableModel) tblAdministrators.getModel();

        model.setRowCount(0);

        try {
            java.nio.file.Path file
                    = java.nio.file.Paths.get("administrators.txt");

            if (!java.nio.file.Files.exists(file)) {
                return;
            }

            for (String line : java.nio.file.Files.readAllLines(file)) {
                String[] data = line.split("\\|", -1);

                if (data.length == 3) {
                    model.addRow(new Object[]{
                        data[0],
                        data[1],
                        data[2]
                    });
                }
            }

        } catch (java.io.IOException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Could not load administrators: "
                    + ex.getMessage());
        }
    }//GEN-LAST:event_AddButtonActionPerformed

    private void searchAdministrator() {
        String keyword = txtSearch.getText().trim().toLowerCase();

        javax.swing.table.DefaultTableModel model
                = (javax.swing.table.DefaultTableModel) tblAdministrators.getModel();

        model.setRowCount(0);

        try {
            java.nio.file.Path file
                    = java.nio.file.Paths.get("administrators.txt");

            if (!java.nio.file.Files.exists(file)) {
                return;
            }

            for (String line : java.nio.file.Files.readAllLines(file)) {
                String[] data = line.split("\\|", -1);

                if (data.length == 3
                        && (data[0].toLowerCase().contains(keyword)
                        || data[1].toLowerCase().contains(keyword))) {

                    model.addRow(new Object[]{
                        data[0], data[1], data[2]
                    });
                }
            }

        } catch (java.io.IOException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Search failed: " + ex.getMessage());
        }
    }

